"use client";

import { PurchaseOrderProposal } from "@/lib/api/demandiq";
import {
  X,
  FileSpreadsheet,
  Download,
  Printer,
  Copy,
  Check,
  ShieldCheck,
  Building,
  Calendar,
  AlertCircle,
} from "lucide-react";
import { useState } from "react";
import { toast } from "@/context/ToastContext";

interface Props {
  po: PurchaseOrderProposal | null;
  onClose: () => void;
}

export function PurchaseOrderModal({ po, onClose }: Props) {
  const [copied, setCopied] = useState(false);

  if (!po) return null;

  const handleCopy = () => {
    const text = `SHOPNEST DEMANDIQ PURCHASE ORDER
PO Number: ${po.poNumber}
Generated: ${new Date(po.createdAt).toLocaleDateString()}
Target SLA: ${po.targetServiceLevel}
Store: ${po.storeName}
Total Units: ${po.totalUnitsToOrder}
Estimated Investment: $${po.totalEstimatedInvestment.toLocaleString()}
Protected Revenue: $${po.totalProtectedRevenue.toLocaleString()}

ITEMS:
${po.items
  .map(
    (it) =>
      `- [${it.sku}] ${it.title} | Reorder: ${it.suggestedReorderQty} units | Est Cost: $${it.lineTotal.toLocaleString()}`
  )
  .join("\n")}
`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    toast.success("Purchase Order copied to clipboard!");
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadJson = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(po, null, 2));
    const downloadAnchor = document.createElement("a");
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `${po.poNumber}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
    toast.success("PO downloaded as JSON!");
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-sm p-4 overflow-y-auto">
      <div className="relative w-full max-w-3xl rounded-3xl border border-border/80 bg-card p-6 shadow-2xl animate-in fade-in zoom-in-95 duration-200 my-8">
        {/* Header */}
        <div className="flex items-start justify-between border-b border-border/40 pb-4">
          <div>
            <div className="flex items-center gap-2">
              <span className="flex h-7 w-7 items-center justify-center rounded-xl bg-indigo-500/10 text-indigo-500">
                <FileSpreadsheet className="h-4 w-4" />
              </span>
              <span className="font-mono text-xs font-bold text-indigo-500 uppercase">{po.poNumber}</span>
              <span className="rounded-full bg-emerald-500/10 border border-emerald-500/20 px-2 py-0.5 text-[10px] font-bold text-emerald-500">
                SLA: {po.targetServiceLevel}
              </span>
            </div>
            <h3 className="mt-1 font-extrabold text-foreground text-lg">Official Replenishment Purchase Order</h3>
            <p className="text-xs text-muted-foreground">
              Automated EOQ replenishment proposal generated by DemandIQ Inventory Engine.
            </p>
          </div>

          <button
            onClick={onClose}
            className="flex h-8 w-8 items-center justify-center rounded-xl hover:bg-muted text-muted-foreground transition-colors"
          >
            <X className="h-4 w-4" />
          </button>
        </div>

        {/* PO Meta Details */}
        <div className="mt-4 grid grid-cols-2 md:grid-cols-4 gap-3 text-xs bg-muted/30 border border-border/40 rounded-2xl p-4">
          <div>
            <span className="text-[10px] uppercase text-muted-foreground font-semibold">Store</span>
            <p className="font-bold text-foreground mt-0.5 flex items-center gap-1.5">
              <Building className="h-3 w-3 text-indigo-500" />
              {po.storeName}
            </p>
          </div>
          <div>
            <span className="text-[10px] uppercase text-muted-foreground font-semibold">Generated Date</span>
            <p className="font-bold text-foreground mt-0.5 flex items-center gap-1.5">
              <Calendar className="h-3 w-3 text-indigo-500" />
              {new Date(po.createdAt).toLocaleDateString()}
            </p>
          </div>
          <div>
            <span className="text-[10px] uppercase text-muted-foreground font-semibold">Lead Time SLA</span>
            <p className="font-bold text-foreground mt-0.5">{po.leadTimeAssumptionDays} Days Cycle</p>
          </div>
          <div>
            <span className="text-[10px] uppercase text-muted-foreground font-semibold">Valid Until</span>
            <p className="font-bold text-foreground mt-0.5">{po.validUntil}</p>
          </div>
        </div>

        {/* Items Table */}
        <div className="mt-5 overflow-x-auto rounded-2xl border border-border/40">
          <table className="w-full text-xs">
            <thead>
              <tr className="border-b border-border/40 bg-muted/40 text-[10px] uppercase text-muted-foreground text-left">
                <th className="p-3">SKU</th>
                <th className="p-3">Product Title</th>
                <th className="p-3 text-center">Stock</th>
                <th className="p-3 text-center">Velocity</th>
                <th className="p-3 text-center text-indigo-500 font-bold">Suggested Qty</th>
                <th className="p-3 text-right">Unit Cost</th>
                <th className="p-3 text-right">Line Total</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-border/30">
              {po.items.map((it) => (
                <tr key={it.productId} className="hover:bg-muted/20">
                  <td className="p-3 font-mono font-bold text-indigo-500">{it.sku}</td>
                  <td className="p-3 font-medium text-foreground max-w-[200px] truncate">{it.title}</td>
                  <td className="p-3 text-center font-mono">{it.currentStock}</td>
                  <td className="p-3 text-center font-mono text-muted-foreground">{it.dailyVelocity}u/d</td>
                  <td className="p-3 text-center font-mono font-black text-indigo-600 bg-indigo-500/5">
                    +{it.suggestedReorderQty}
                  </td>
                  <td className="p-3 text-right font-mono">${it.estimatedUnitCost}</td>
                  <td className="p-3 text-right font-mono font-bold text-foreground">
                    ${it.lineTotal.toLocaleString()}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>

        {/* Totals Summary */}
        <div className="mt-5 flex flex-col md:flex-row items-center justify-between gap-4 rounded-2xl border border-indigo-500/20 bg-indigo-500/5 p-4 text-xs">
          <div className="space-y-1">
            <div className="flex items-center gap-2">
              <ShieldCheck className="h-4 w-4 text-emerald-500" />
              <span className="font-bold text-foreground">Protected Revenue:</span>
              <span className="font-mono font-bold text-emerald-600">
                +${po.totalProtectedRevenue.toLocaleString()}
              </span>
            </div>
            <p className="text-[11px] text-muted-foreground">{po.notes}</p>
          </div>

          <div className="text-right">
            <span className="text-[10px] uppercase text-muted-foreground font-semibold">Total Estimated Investment</span>
            <p className="text-2xl font-black text-foreground font-mono">
              ${po.totalEstimatedInvestment.toLocaleString()}
            </p>
            <span className="text-[10px] text-muted-foreground font-mono">
              Total {po.totalUnitsToOrder} Units
            </span>
          </div>
        </div>

        {/* Action Buttons */}
        <div className="mt-6 flex flex-wrap items-center justify-end gap-3 border-t border-border/40 pt-4 text-xs">
          <button
            onClick={handleCopy}
            className="inline-flex items-center gap-1.5 rounded-xl border border-border/60 bg-card px-4 py-2 font-medium text-foreground hover:bg-muted transition-colors"
          >
            {copied ? <Check className="h-3.5 w-3.5 text-emerald-500" /> : <Copy className="h-3.5 w-3.5" />}
            {copied ? "Copied" : "Copy Text"}
          </button>

          <button
            onClick={handleDownloadJson}
            className="inline-flex items-center gap-1.5 rounded-xl border border-border/60 bg-card px-4 py-2 font-medium text-foreground hover:bg-muted transition-colors"
          >
            <Download className="h-3.5 w-3.5" />
            Download JSON
          </button>

          <button
            onClick={handlePrint}
            className="inline-flex items-center gap-1.5 rounded-xl bg-gradient-to-r from-indigo-600 to-violet-600 px-5 py-2 font-semibold text-white shadow-md hover:from-indigo-500 hover:to-violet-500 transition-all"
          >
            <Printer className="h-3.5 w-3.5" />
            Print Purchase Order
          </button>
        </div>
      </div>
    </div>
  );
}
